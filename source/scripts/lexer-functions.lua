for _, group in pairs(strings) do
  for _, val in ipairs(group) do
    if not group[val] then
      group[val] = true;
    end

    if group == strings.craft or group == strings.produce then
      if not strings.item[val] then
        strings.item[val] = true;
        strings.item[#strings.item+1] = val;
      end
    end
  end
end

